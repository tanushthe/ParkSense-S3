import os, zipfile
import numpy as np
import tensorflow as tf

# 1. Locate and unzip parking_crops.zip
zip_path = "/parking_crops.zip" if os.path.exists("/parking_crops.zip") else "/content/parking_crops.zip"
DATASET_DIR = "/content/parking_dataset"
with zipfile.ZipFile(zip_path, "r") as z:
    z.extractall(DATASET_DIR)

# 2. Load empty/ and occupied/ folders (80% train, 20% validation)
IMG_SIZE = (48, 48)
BATCH_SIZE = 8

train_ds = tf.keras.utils.image_dataset_from_directory(
    DATASET_DIR,
    validation_split=0.2,
    subset="training",
    seed=42,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="binary",
)
val_ds = tf.keras.utils.image_dataset_from_directory(
    DATASET_DIR,
    validation_split=0.2,
    subset="validation",
    seed=42,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    label_mode="binary",
)

print("Classes:", train_ds.class_names)  # 0 = empty, 1 = occupied

# 3. Data augmentation to prevent overfitting on 48 images
augment = tf.keras.Sequential([
    tf.keras.layers.RandomFlip("horizontal"),
    tf.keras.layers.RandomBrightness(0.25),
    tf.keras.layers.RandomContrast(0.25),
    tf.keras.layers.RandomRotation(0.05),
    tf.keras.layers.RandomZoom(0.1),
])

norm_train = train_ds.map(lambda x, y: (augment(x, training=True) / 255.0, y))
norm_val = val_ds.map(lambda x, y: (x / 255.0, y))

# 4. Build TinyML-friendly CNN
model = tf.keras.Sequential([
    tf.keras.layers.Input(shape=(48, 48, 3)),
    tf.keras.layers.Conv2D(16, 3, strides=2, padding="same", activation="relu"),
    tf.keras.layers.SeparableConv2D(24, 3, strides=2, padding="same", activation="relu"),
    tf.keras.layers.SeparableConv2D(32, 3, strides=2, padding="same", activation="relu"),
    tf.keras.layers.GlobalAveragePooling2D(),
    tf.keras.layers.Dropout(0.3),
    tf.keras.layers.Dense(1, activation="sigmoid"),
])

model.compile(
    optimizer=tf.keras.optimizers.Adam(1e-3),
    loss="binary_crossentropy",
    metrics=["accuracy"],
)

history = model.fit(norm_train, validation_data=norm_val, epochs=50)

# 5. Full INT8 Post-Training Quantization
def representative_dataset():
    for images, _ in norm_train.unbatch().batch(1).take(100):
        yield [tf.cast(images, tf.float32)]

converter = tf.lite.TFLiteConverter.from_keras_model(model)
converter.optimizations = [tf.lite.Optimize.DEFAULT]
converter.representative_dataset = representative_dataset
converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
converter.inference_input_type = tf.int8
converter.inference_output_type = tf.int8

tflite_model = converter.convert()
with open("/content/parking_model_int8.tflite", "wb") as f:
    f.write(tflite_model)

# 6. Export C Header (alignas(16) for ESP32-S3 SIMD optimization)
with open("/content/model_data.h", "w") as f:
    f.write("#pragma once\n#include <cstdint>\n\n")
    f.write("alignas(16) const unsigned char g_parking_model_data[] = {\n")
    for i, b in enumerate(tflite_model):
        if i % 12 == 0:
            f.write("  ")
        f.write(f"0x{b:02x}, ")
        if (i + 1) % 12 == 0:
            f.write("\n")
    f.write("\n};\n")
    f.write(f"const int g_parking_model_data_len = {len(tflite_model)};\n")

# Auto-trigger browser download of both files
from google.colab import files
